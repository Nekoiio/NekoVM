program3 = bytes([
    # -----------------------------
    # MOV
    # -----------------------------

    0x01, 0x00, 0x0A,       # MOV R0, 0x0A
    0x01, 0x01, 0x05,       # MOV R1, 0x05
    0x09, 0x02, 0x00,       # MOV R2, R0

    # -----------------------------
    # ADD
    # -----------------------------

    0x02, 0x00, 0x01,       # ADD R0, R1       (10 + 5 = 15)
    0x03, 0x00, 0x05,       # ADD R0, 0x05     (15 + 5 = 20)

    # -----------------------------
    # SUB
    # -----------------------------

    0x04, 0x00, 0x01,       # SUB R0, R1       (20 - 5 = 15)
    0x05, 0x00, 0x05,       # SUB R0, 0x05     (15 - 5 = 10)

    # -----------------------------
    # CMP
    # -----------------------------

    0x06, 0x00, 0x01,       # CMP R0, R1       (10 vs 5 -> ZF=0)
    0x07, 0x00, 0x0A,       # CMP R0, 0x0A     (10 vs 10 -> ZF=1)

    # -----------------------------
    # JZ
    # -----------------------------

    0x09, 0x21, 0x00,       # JZ 0x0021

    # This should be skipped because ZF=1
    0x01, 0x03, 0xFF,       # MOV R3, 0xFF

    # -----------------------------
    # PUSH / POP
    # -----------------------------

    0x11, 0x01,             # PUSH R1
    0x12, 0x42,             # PUSH 0x42
    0x13, 0x03,             # POP R3
    0x13, 0x02,             # POP R2

    # -----------------------------
    # JMP
    # -----------------------------

    0x08, 0x2C, 0x00,       # JMP 0x0036

    # -----------------------------
    # STP
    # -----------------------------

    0xFF                    # STP
])

